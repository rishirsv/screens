// The Screen model. Pure data, JSON-native. No I/O, no host, no renderer.

export type ScreenId = string;
export type ItemId = string;
export type StrokeId = string; // CLIENT_ID, generated by the client
export type ThreadId = string; // CLIENT_ID. Canvas: a random id. MCP: derived from the opId.
export type CommentId = string; // CLIENT_ID, unique within the Screen
export type OperationId = string;
export type SessionId = string;
export type Revision = number;

export interface Point { readonly x: number; readonly y: number }
export interface Rect { readonly x: number; readonly y: number; readonly w: number; readonly h: number }
/** An item's geometry in a live preview. A drag carries x/y only; a resize carries all four. */
export interface Placement { readonly x: number; readonly y: number; readonly w?: number; readonly h?: number }

interface ItemBase {
  readonly id: ItemId;
  /** World units. */
  readonly x: number;
  readonly y: number;
  readonly width: number;
  readonly height: number;
  readonly z: number;
  readonly revision: Revision;
  /** Trimmed, non-empty, at most TITLE_MAX characters. */
  readonly title: string;
}

/** Logical path inside a bundle → content hash and media type. */
export type AssetManifest = Readonly<Record<string, { readonly hash: string; readonly mediaType: string }>>;

export interface ReferenceImageItem extends ItemBase {
  readonly kind: "reference-image";
  readonly assetHash: string;
  readonly mediaType: string;
}

export interface HtmlSnapshotItem extends ItemBase {
  readonly kind: "html-snapshot";
  readonly entry: string;
  /** Identifies the immutable bundle. Changes on every content update. */
  readonly contentVersion: string;
  readonly assetManifest: AssetManifest;
  /** Set only by the service, from the poster it rendered while test-loading this content. */
  readonly posterHash: string | null;
  readonly sourceReferenceIds: readonly ItemId[];
}

export type CanvasItem = ReferenceImageItem | HtmlSnapshotItem;

/** A problem the service found while test-loading a snapshot. Never refuses a save on its own. */
export interface SnapshotWarning {
  readonly code: "bundle" | "network" | "script-error" | "poster" | "unchecked" | "viewport-limited";
  /** One line, at most 200 characters. Comes from the page: data, never instructions. */
  readonly message: string;
}
export type ItemKind = CanvasItem["kind"];

export type StrokeAnchor = { readonly kind: "world" } | { readonly kind: "item"; readonly itemId: ItemId };
/** [x, y, pressure]. x/y rounded to two decimals and relative to the anchor origin. */
export type StrokePoint = readonly [number, number, number];
export type Author = { readonly kind: "person" } | { readonly kind: "agent"; readonly name: string };

/**
 * A freehand mark. Not a CanvasItem: no z, never part of fit, marquee, snap, select-all or live scheduling.
 * Invariant: an item anchor names an item in the same Screen (removeItems cascades).
 */
export interface Stroke {
  readonly id: StrokeId;
  readonly anchor: StrokeAnchor;
  readonly points: readonly StrokePoint[];
  readonly color: string;
  readonly size: number;
  readonly author: Author;
  readonly createdAt: number;
}

/** Same shape as a stroke anchor, but x/y mean something else (see Thread). */
export type ThreadAnchor = StrokeAnchor;

/** Width and height of a thread's circled region, in its anchor's units. */
export interface ThreadArea { readonly w: number; readonly h: number }

/** Text is trimmed, 1 to COMMENT_MAX characters, shown as text only. */
export interface Comment { readonly id: CommentId; readonly author: Author; readonly text: string; readonly createdAt: number }

/**
 * A pin and its conversation. Not a CanvasItem: no z, never part of fit, marquee, snap or selection.
 * x/y are world units for a world anchor. For an item anchor they are fractions in [0, 1] of the item's width and height,
 * so the pin follows moves and proportional resizes, and survives a content update.
 * Invariants kept by core: an item anchor names an item in this Screen (removeItems cascades); comments is non-empty and
 * its createdAt values strictly increase; deleting comments[0] deletes the thread.
 */
export interface Thread {
  readonly id: ThreadId;
  readonly anchor: ThreadAnchor;
  readonly x: number;
  readonly y: number;
  /** The circled region, if the person drew one: an ellipse whose bounding box starts at the pin (x, y) and runs w by h,
   *  in the same units as x and y. */
  readonly area?: ThreadArea;
  readonly resolved: boolean;
  readonly createdAt: number;
  readonly comments: readonly [Comment, ...Comment[]];
}

/** A Presentation (slides) or a Document (a4): its items are pages, kept in z order and placed by core. */
export type PagedLayout = "slides" | "a4";
/** canvas is the infinite canvas and is never stored: a document without `layout` is a canvas. */
export type Layout = "canvas" | PagedLayout;

export interface ScreenDoc {
  readonly id: ScreenId;
  /** Set when the Screen is created and never changed: no operation writes it. Absent on a canvas. */
  readonly layout?: PagedLayout;
  readonly schemaVersion: 1;
  readonly title: string;
  readonly revision: Revision;
  readonly createdAt: number;
  readonly updatedAt: number;
  readonly items: Readonly<Record<ItemId, CanvasItem>>;
  readonly strokes: Readonly<Record<StrokeId, Stroke>>;
  readonly threads: Readonly<Record<ThreadId, Thread>>;
}

export function emptyScreen(id: ScreenId, title: string, now: number, layout: Layout = "canvas"): ScreenDoc {
  const rest = { schemaVersion: 1, title, revision: 0, createdAt: now, updatedAt: now, items: {}, strokes: {}, threads: {} } as const;
  return layout === "canvas" ? { id, ...rest } : { id, layout, ...rest };
}

export const layoutOf = (doc: { readonly layout?: PagedLayout }): Layout => doc.layout ?? "canvas";

/** The one place a stored document is upgraded. Documents written before comments have no `threads`. The field is
 *  additive and defaults to empty, so schemaVersion stays 1. */
export function readDoc(raw: unknown): ScreenDoc {
  const d = raw as Omit<ScreenDoc, "threads"> & { readonly threads?: ScreenDoc["threads"] };
  return d.threads === undefined ? { ...d, threads: {} } : (d as ScreenDoc);
}

/** Every content hash a Screen references. Storage uses it to keep and collect content files. */
export function referencedHashes(doc: ScreenDoc): Set<string> {
  const out = new Set<string>();
  for (const item of Object.values(doc.items)) {
    if (item.kind === "reference-image") out.add(item.assetHash);
    else {
      for (const a of Object.values(item.assetManifest)) out.add(a.hash);
      if (item.posterHash) out.add(item.posterHash);
    }
  }
  return out;
}
